import os
import io
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_match_pdf_report(match_data: dict, output_path: str):
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        rightMargin=40, leftMargin=40,
        topMargin=40, bottomMargin=40
    )
    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'MatchTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=26,
        textColor=colors.HexColor('#1E1B4B')
    )
    sub_style = ParagraphStyle(
        'MatchSub',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=11,
        leading=14,
        textColor=colors.HexColor('#6B7280')
    )
    h2_style = ParagraphStyle(
        'SectionHeader',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#4338CA')
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#1F2937')
    )

    elements = []

    # Header
    elements.append(Paragraph("CRICKETVERSE AI — OFFICIAL MATCH INTELLIGENCE REPORT", sub_style))
    elements.append(Spacer(1, 4))
    elements.append(Paragraph(f"{match_data.get('title', 'T20 Championship Match')}", title_style))
    elements.append(Paragraph(f"Venue: {match_data.get('venue', 'Melbourne Cricket Ground')} | Format: {match_data.get('match_type', 'T20')}", sub_style))
    elements.append(Spacer(1, 10))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#6366F1'), spaceBefore=5, spaceAfter=15))

    # Match Summary Table
    elements.append(Paragraph("MATCH SUMMARY & SCORECARD", h2_style))
    elements.append(Spacer(1, 6))

    summary_data = [
        ["Match Status", match_data.get("status", "Completed").upper()],
        ["Toss Winner", f"{match_data.get('toss_winner', 'N/A')} (Chose to {match_data.get('toss_decision', 'bat')})"],
        ["Winner", f"{match_data.get('winner', 'N/A')} ({match_data.get('win_margin', '')})"],
        ["Current Run Rate", f"{match_data.get('current_rr', 0.0):.2f} RPO"],
        ["Required Run Rate", f"{match_data.get('required_rr', 0.0):.2f} RPO"]
    ]
    t = Table(summary_data, colWidths=[180, 320])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('TEXTCOLOR', (0,0), (-1,-1), colors.HexColor('#0F172A')),
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0'))
    ]))
    elements.append(t)
    elements.append(Spacer(1, 15))

    # AI Tactical Insights
    elements.append(Paragraph("AI TACTICAL INSIGHTS & PROJECTIONS", h2_style))
    elements.append(Spacer(1, 6))
    insights = match_data.get("tactical_insights", [
        "Pitch wear accelerated spin turn by 1.8° in the second innings.",
        "Middle-overs boundary starvation (overs 7-15) was the critical phase swing.",
        "Yorker execution rate of 78% in death overs restricted boundary frequency."
    ])
    for ins in insights:
        elements.append(Paragraph(f"• {ins}", body_style))
        elements.append(Spacer(1, 4))

    elements.append(Spacer(1, 20))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#CBD5E1'), spaceBefore=5, spaceAfter=10))
    elements.append(Paragraph("Generated by CricketVerse AI Intelligence Engine • http://cricketverse.ai", sub_style))

    doc.build(elements)
    return output_path
